def load_rows():
    rows = list(csv.reader(open(LEDGER, encoding="utf-8-sig")))
    body = [r + [""] * (5 - len(r)) if len(r) < 5 else r[:5] for r in rows[1:]]
    return body


def table(headers, data):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in data:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |")
    return "\n".join(out)


