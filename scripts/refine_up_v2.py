def apply_corrections(text, dry_run=False):
    """应用所有修正规则，返回 (修正后文本, 修正日志列表)"""
    log = []
    for rule in CORRECTIONS:
        if len(rule) == 3:
            pattern, replacement, desc = rule
            try:
                new_text, count = re.subn(pattern, replacement, text)
            except Exception as e:
                print(f"  [WARN] 规则 [{desc}] 执行失败: {e}")
                continue
            if count > 0:
                log.append(f"  [{desc}] x{count}")
                text = new_text
    return text, log


def check_manual_items(text):
    """检查需要人工确认的条目"""
    findings = []
    for pattern, note in MANUAL_CHECK:
        matches = list(re.finditer(pattern, text))
        if matches:
            for m in matches:
                start = max(0, m.start() - 20)
                end = min(len(text), m.end() + 20)
                context = text[start:end].replace('\n', ' ')
                findings.append(f"  [{note}] @pos{m.start()}: ...{context}...")
    return findings


def refine_file(filepath, dry_run=False):
    """精修单个文件"""
    with open(filepath, 'r', encoding='utf-8') as f:
        original = f.read()
    
    size_before = len(original)
    
    # 应用修正
    corrected, fix_log = apply_corrections(original, dry_run)
    
    # 检查人工确认项
    manual_findings = check_manual_items(corrected)
    
    size_after = len(corrected)
    
    stats = {
        'file': os.path.basename(filepath),
        'size_before': size_before,
        'size_after': size_after,
        'fixes': len(fix_log),
        'fix_details': fix_log,
        'manual_findings': manual_findings,
    }
    
    if not dry_run and corrected != original:
        # 备份
        backup_path = str(filepath) + '.v2_backup'
        with open(backup_path, 'w', encoding='utf-8') as f:
            f.write(original)
        
        # 写入修正版
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(corrected)
    
    return stats


