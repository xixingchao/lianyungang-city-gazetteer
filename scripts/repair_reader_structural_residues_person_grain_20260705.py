    changes = []

    count = html.count(GRAIN_DUPLICATE_BLOCK)
    if count != 1:
        raise RuntimeError(f"expected grain duplicate block once, got {count}")
    html = html.replace(GRAIN_DUPLICATE_BLOCK + "\n", "", 1)
    changes.append({"label": "删除粮食合同定购重复碎片", "count": 1})

